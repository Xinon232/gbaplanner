#!/usr/bin/env python3
"""Builds include/app/ui_font_data.h: the two interface fonts as 1-bit rows.

- UNSCII 16 (8x16 cells, 8 px advance): menus, settings, the calendar grid.
  Source: references/fonts/unscii_16.bmp (the Butano sprite font of gbavocab,
  UNSCII by Viznut, see references/fonts/UNSCII-LICENSE.txt).
- The gbamp3 5x7 font in 16 px cells (6 px advance): small titles, weekday
  row, grey hints. Source: references/fonts/gbamp3_small.bmp (gbavocab's
  ui_font, Halim Jarrar, GPL-3.0-or-later, see
  references/fonts/GBAMP3-FONT-LICENSE.txt).

Both bitmaps hold one 8x16 cell per character from '!' to '~', then the extra
UTF-8 characters listed below. A few characters the screens need and the
bitmaps lack (middle dot, check mark, notes marker, ellipsis, the
Settings page arrow) are drawn here in the same style.
The app draws these rows into its 8 bpp bitmap screen itself (no sprites).

Usage: python3 tools/build_ui_fonts.py   (deterministic; needs Pillow)
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
FONTS = [
    ('unscii16', 'unscii_16.bmp', 'ÁÉÍÓÚÜÑáéíóúüñ¡¿', 8),
    ('small', 'gbamp3_small.bmp', 'ÁÉÍÓÚÜÑáéíóúüñ¡¿°', 6),
]

# Extra glyphs drawn here: rows of 8 bits (bit 7 = leftmost pixel).
EXTRA = {
    'unscii16': {
        '·': [0] * 6 + [0x18, 0x18] + [0] * 8,
        # Ticked to-dos, notes marker, "Loading…" (not in UNSCII's bitmap).
        '✓': [0, 0, 0, 0x03, 0x03, 0x06, 0x06, 0xcc, 0xcc, 0x78, 0x78, 0x30, 0, 0, 0, 0],
        '≡': [0, 0, 0, 0, 0x7e, 0, 0, 0x7e, 0, 0, 0x7e, 0, 0, 0, 0, 0],
        '…': [0] * 10 + [0xdb, 0xdb] + [0] * 4,
        # Settings rows that open a page.
        '▸': [0] * 4 + [0x20, 0x30, 0x38, 0x3c, 0x38, 0x30, 0x20] + [0] * 5,
    },
    'small': {
        '·': [0] * 8 + [0x20] + [0] * 7,
        '✓': [0] * 5 + [0x08, 0x08, 0x10, 0xa0, 0xa0, 0x40] + [0] * 5,
        '≡': [0] * 6 + [0xf8, 0, 0xf8, 0, 0xf8] + [0] * 5,
        '…': [0] * 11 + [0xa8] + [0] * 4,
    },
}


def rows_of(image, index):
    px = image.load()
    out = []
    for y in range(16):
        bits = 0
        for x in range(8):
            if px[x, index * 16 + y] != 0:
                bits |= 0x80 >> x
        out.append(bits)
    return out


def main():
    lines = ['// Generated by tools/build_ui_fonts.py -- do not edit.',
             '// UNSCII 16 (Viznut, GPL with font exception) and the gbamp3 5x7',
             '// font (GPL-3.0-or-later) as 16 rows of 8 bits per character (bit 7 = left).',
             '#pragma once', '#include <cstdint>', '', 'namespace app::fontdata {', '']
    for name, bmp, utf8, advance in FONTS:
        image = Image.open(ROOT / 'references' / 'fonts' / bmp)
        count = image.size[1] // 16
        glyphs = [rows_of(image, i) for i in range(count)]
        ascii_count = 126 - 33 + 1
        assert count == ascii_count + len(utf8), (bmp, count)
        extra_chars = list(utf8)
        for ch, rows in EXTRA[name].items():
            extra_chars.append(ch)
            glyphs.append(rows)
        lines.append(f'constexpr int {name}_advance = {advance};')
        lines.append(f'constexpr int {name}_count = {len(glyphs)};')
        lines.append(f'// Characters after the ASCII range, in glyph order.')
        lines.append(f'constexpr uint16_t {name}_extra[] = {{' +
                     ', '.join(f'0x{ord(c):04x}' for c in extra_chars) + '};')
        lines.append(f'constexpr uint8_t {name}_rows[{len(glyphs)}][16] = {{')
        for i, rows in enumerate(glyphs):
            ch = chr(33 + i) if i < ascii_count else extra_chars[i - ascii_count]
            label = {'\\': 'backslash'}.get(ch, ch)
            lines.append('    {' + ','.join(f'0x{r:02x}' for r in rows) + '},  // ' + label)
        lines.append('};')
        lines.append('')
    lines.append('}  // namespace app::fontdata')
    out = ROOT / 'include' / 'app' / 'ui_font_data.h'
    out.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('Wrote', out)


if __name__ == '__main__':
    main()
